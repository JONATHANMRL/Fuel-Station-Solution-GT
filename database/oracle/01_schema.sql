CREATE TABLE ROLES (
    ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(255),
    ACTIVO NUMBER(1) DEFAULT 1 CHECK (ACTIVO IN (0, 1)),
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE USUARIOS (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(80) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ID_ROL NUMBER NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 CHECK (ACTIVO IN (0, 1)),
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_USUARIOS_ROLES FOREIGN KEY (ID_ROL) REFERENCES ROLES(ID_ROL)
);

CREATE INDEX IDX_USUARIOS_EMAIL ON USUARIOS(EMAIL);

CREATE TABLE MARCAS (
    ID_MARCA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(80) NOT NULL UNIQUE,
    DESCRIPCION VARCHAR2(255),
    ACTIVA NUMBER(1) DEFAULT 1 CHECK (ACTIVA IN (0, 1)),
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE GASOLINERAS (
    ID_GASOLINERA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(120) NOT NULL,
    ID_MARCA NUMBER,
    DIRECCION VARCHAR2(220) NOT NULL,
    MUNICIPIO VARCHAR2(80) NOT NULL,
    ZONA VARCHAR2(80),
    COLONIA VARCHAR2(100),
    LATITUD NUMBER(10,7) NOT NULL,
    LONGITUD NUMBER(10,7) NOT NULL,
    ACTIVA NUMBER(1) DEFAULT 1 CHECK (ACTIVA IN (0, 1)),
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_GASOLINERAS_MARCAS FOREIGN KEY (ID_MARCA) REFERENCES MARCAS(ID_MARCA)
);

CREATE INDEX IDX_GASOLINERAS_MUNICIPIO ON GASOLINERAS(MUNICIPIO);
CREATE INDEX IDX_GASOLINERAS_MARCA ON GASOLINERAS(ID_MARCA);

CREATE TABLE COMBUSTIBLES (
    ID_COMBUSTIBLE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(40) NOT NULL UNIQUE,
    TIPO VARCHAR2(30) NOT NULL CHECK (TIPO IN ('REGULAR', 'SUPERIOR', 'DIESEL')),
    ACTIVO NUMBER(1) DEFAULT 1 CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE PRECIOS (
    ID_PRECIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_GASOLINERA NUMBER NOT NULL,
    ID_COMBUSTIBLE NUMBER NOT NULL,
    PRECIO NUMBER(8,2) NOT NULL CHECK (PRECIO > 0),
    FECHA_ACTUALIZACION TIMESTAMP DEFAULT SYSTIMESTAMP,
    ID_USUARIO NUMBER NOT NULL,
    CONSTRAINT FK_PRECIOS_GASOLINERAS FOREIGN KEY (ID_GASOLINERA) REFERENCES GASOLINERAS(ID_GASOLINERA),
    CONSTRAINT FK_PRECIOS_COMBUSTIBLES FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLES(ID_COMBUSTIBLE),
    CONSTRAINT FK_PRECIOS_USUARIOS FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO)
);

CREATE INDEX IDX_PRECIOS_GASOLINERA ON PRECIOS(ID_GASOLINERA, FECHA_ACTUALIZACION);
CREATE INDEX IDX_PRECIOS_COMBUSTIBLE ON PRECIOS(ID_COMBUSTIBLE, FECHA_ACTUALIZACION);

CREATE TABLE HISTORIAL_PRECIOS (
    ID_HISTORIAL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_GASOLINERA NUMBER NOT NULL,
    ID_COMBUSTIBLE NUMBER NOT NULL,
    PRECIO_ANTERIOR NUMBER(8,2) NOT NULL,
    PRECIO_NUEVO NUMBER(8,2) NOT NULL,
    FECHA_CAMBIO TIMESTAMP DEFAULT SYSTIMESTAMP,
    ID_USUARIO NUMBER NOT NULL,
    MOTIVO VARCHAR2(200),
    CONSTRAINT FK_HISTORIAL_GASOLINERAS FOREIGN KEY (ID_GASOLINERA) REFERENCES GASOLINERAS(ID_GASOLINERA),
    CONSTRAINT FK_HISTORIAL_COMBUSTIBLES FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES COMBUSTIBLES(ID_COMBUSTIBLE),
    CONSTRAINT FK_HISTORIAL_USUARIOS FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO)
);

CREATE TABLE FAVORITOS (
    ID_FAVORITO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO NUMBER NOT NULL,
    ID_GASOLINERA NUMBER NOT NULL,
    FECHA_AGREGADO TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_FAVORITOS_USUARIOS FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO),
    CONSTRAINT FK_FAVORITOS_GASOLINERAS FOREIGN KEY (ID_GASOLINERA) REFERENCES GASOLINERAS(ID_GASOLINERA),
    CONSTRAINT UQ_FAVORITOS UNIQUE (ID_USUARIO, ID_GASOLINERA)
);

CREATE TABLE SUSCRIPCIONES_PUSH (
    ID_SUSCRIPCION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO NUMBER,
    ENDPOINT VARCHAR2(500) NOT NULL,
    AUTH VARCHAR2(200) NOT NULL,
    P256DH VARCHAR2(255) NOT NULL,
    ACTIVA NUMBER(1) DEFAULT 1 CHECK (ACTIVA IN (0, 1)),
    FECHA_CREACION TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_SUSCRIPCIONES_USUARIOS FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO)
);

CREATE TABLE NOTIFICACIONES (
    ID_NOTIFICACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO NUMBER,
    ID_GASOLINERA NUMBER,
    TITULO VARCHAR2(120) NOT NULL,
    MENSAJE VARCHAR2(500) NOT NULL,
    TIPO VARCHAR2(25) DEFAULT 'INFO' CHECK (TIPO IN ('INFO', 'SUBIDA', 'BAJADA', 'ALERTA')),
    ENVIADA NUMBER(1) DEFAULT 0 CHECK (ENVIADA IN (0, 1)),
    FECHA_ENVIO TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_NOTIFICACIONES_USUARIOS FOREIGN KEY (ID_USUARIO) REFERENCES USUARIOS(ID_USUARIO),
    CONSTRAINT FK_NOTIFICACIONES_GASOLINERAS FOREIGN KEY (ID_GASOLINERA) REFERENCES GASOLINERAS(ID_GASOLINERA)
);

CREATE INDEX IDX_NOTIFICACIONES_USUARIO ON NOTIFICACIONES(ID_USUARIO, FECHA_ENVIO);
CREATE INDEX IDX_NOTIFICACIONES_GASOLINERA ON NOTIFICACIONES(ID_GASOLINERA, FECHA_ENVIO);
