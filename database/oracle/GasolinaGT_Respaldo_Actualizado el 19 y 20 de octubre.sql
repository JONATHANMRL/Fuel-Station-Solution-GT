  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_MAPA_GASOLINERA" ("ID_GASOLINERA", "GASOLINERA", "MARCA", "DIRECCION", "MUNICIPIO", "DEPARTAMENTO", "LATITUD", "LONGITUD", "ESTADO_GASOLINERA", "ID_COMBUSTIBLE", "COMBUSTIBLE", "PRECIO_ACTUAL", "DISPONIBILIDAD") AS 
  SELECT
    G.ID_GASOLINERA,
    G.GASOLINERA,
    M.NOMBRE AS MARCA,
