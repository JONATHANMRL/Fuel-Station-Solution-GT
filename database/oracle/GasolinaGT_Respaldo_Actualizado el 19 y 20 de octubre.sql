  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_GASOLINERA_UBICACION" ("ID_GASOLINERA", "GASOLINERA", "DIRECCION", "MUNICIPIO", "DEPARTAMENTO", "LATITUD", "LONGITUD", "ESTADO") AS 
  SELECT
    G.ID_GASOLINERA,
    G.NOMBRE AS GASOLINERA,
    G.DIRECCION,
    M.NOMBRE AS MUNICIPIO,
    D.NOMBRE AS DEPARTAMENTO,
    G.LATITUD,
    G.LONGITUD,
    G.ESTADO
FROM GASOLINERA G
INNER JOIN MUNICIPIO M
    ON G.ID_MUNICIPIO = M.ID_MUNICIPIO
INNER JOIN DEPARTAMENTO D
    ON M.ID_DEPARTAMENTO = D.ID_DEPARTAMENTO
;
