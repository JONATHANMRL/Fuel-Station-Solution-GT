--  DDL for View V_PRECIO_ACTUAL
--------------------------------------------------------

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_PRECIO_ACTUAL" ("ID_GASOLINERA", "GASOLINERA", "ID_COMBUSTIBLE", "COMBUSTIBLE", "PRECIO_ACTUAL", "DISPONIBILIDAD") AS 
  SELECT
    ID_GASOLINERA,
    GASOLINERA,
    ID_COMBUSTIBLE,
    COMBUSTIBLE,
    PRECIO_ACTUAL,
    DISPONIBILIDAD
FROM (
    SELECT
        G.ID_GASOLINERA,
        G.NOMBRE AS GASOLINERA,
        C.ID_COMBUSTIBLE,
        C.NOMBRE AS COMBUSTIBLE,
        P.PRECIO AS PRECIO_ACTUAL,
        GC.ESTADO AS DISPONIBILIDAD,
        ROW_NUMBER() OVER (
            PARTITION BY P.ID_GASOLINERA, P.ID_COMBUSTIBLE
            ORDER BY P.FECHA_REGISTRO DESC, P.ID_PRECIO DESC
        ) AS RN
    FROM PRECIO P
    INNER JOIN GASOLINERA_COMBUSTIBLE GC
        ON P.ID_GASOLINERA = GC.ID_GASOLINERA
       AND P.ID_COMBUSTIBLE = GC.ID_COMBUSTIBLE
    INNER JOIN GASOLINERA G
        ON GC.ID_GASOLINERA = G.ID_GASOLINERA
    INNER JOIN COMBUSTIBLE C
        ON GC.ID_COMBUSTIBLE = C.ID_COMBUSTIBLE
)
WHERE RN = 1
