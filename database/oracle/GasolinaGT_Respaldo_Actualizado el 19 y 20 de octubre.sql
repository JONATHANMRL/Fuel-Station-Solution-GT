set define off;

  CREATE OR REPLACE EDITIONABLE PROCEDURE "REGISTRAR_PRECIO" (
    P_ID_GASOLINERA IN NUMBER,
    P_ID_COMBUSTIBLE IN NUMBER,
    P_NUEVO_PRECIO IN NUMBER
)
AS
    V_PRECIO_ANTERIOR NUMBER(8,2);
    V_ID_PRECIO NUMBER;
    V_ESTADO VARCHAR2(15);
    V_NOMBRE_GASOLINERA VARCHAR2(100);
    V_NOMBRE_COMBUSTIBLE VARCHAR2(50);
BEGIN
    IF P_NUEVO_PRECIO IS NULL OR P_NUEVO_PRECIO <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'El precio debe ser mayor que cero.');
    END IF;

    SELECT GC.ESTADO, G.NOMBRE, C.NOMBRE
    INTO V_ESTADO, V_NOMBRE_GASOLINERA, V_NOMBRE_COMBUSTIBLE
    FROM GASOLINERA_COMBUSTIBLE GC
    INNER JOIN GASOLINERA G
        ON GC.ID_GASOLINERA = G.ID_GASOLINERA
    INNER JOIN COMBUSTIBLE C
        ON GC.ID_COMBUSTIBLE = C.ID_COMBUSTIBLE
    WHERE GC.ID_GASOLINERA = P_ID_GASOLINERA
      AND GC.ID_COMBUSTIBLE = P_ID_COMBUSTIBLE
      AND GC.ESTADO = 'DISPONIBLE'
      AND G.ESTADO = 'ACTIVA'
      AND C.ESTADO = 'ACTIVO'
    FOR UPDATE OF GC.ESTADO;

    BEGIN
        SELECT PRECIO
        INTO V_PRECIO_ANTERIOR
        FROM (
            SELECT PRECIO
            FROM PRECIO
            WHERE ID_GASOLINERA = P_ID_GASOLINERA
              AND ID_COMBUSTIBLE = P_ID_COMBUSTIBLE
            ORDER BY FECHA_REGISTRO DESC, ID_PRECIO DESC
        )
        WHERE ROWNUM = 1;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            V_PRECIO_ANTERIOR := NULL;
    END;

    INSERT INTO PRECIO (
        ID_GASOLINERA,
        ID_COMBUSTIBLE,
        PRECIO
    )
    VALUES (
        P_ID_GASOLINERA,
        P_ID_COMBUSTIBLE,
        P_NUEVO_PRECIO
    )
    RETURNING ID_PRECIO INTO V_ID_PRECIO;

    IF V_PRECIO_ANTERIOR IS NOT NULL
       AND P_NUEVO_PRECIO < V_PRECIO_ANTERIOR THEN

        FOR R IN (
            SELECT PA.ID_USUARIO
            FROM PREFERENCIA_ALERTA PA
            INNER JOIN USUARIO U
                ON PA.ID_USUARIO = U.ID_USUARIO
            WHERE PA.ID_COMBUSTIBLE = P_ID_COMBUSTIBLE
              AND PA.ESTADO = 'ACTIVA'
              AND U.ESTADO = 'ACTIVO'
              AND P_NUEVO_PRECIO <= PA.PRECIO_MAXIMO
        )
        LOOP
            INSERT INTO NOTIFICACION (
                ID_USUARIO,
                ID_PRECIO,
                MENSAJE,
                PRECIO_ANTERIOR,
                ESTADO
            )
            VALUES (
                R.ID_USUARIO,
                V_ID_PRECIO,
                SUBSTR(
                    'Bajo el precio de ' || V_NOMBRE_COMBUSTIBLE ||
                    ' en ' || V_NOMBRE_GASOLINERA ||
                    '. Nuevo precio: Q' ||
                    TO_CHAR(P_NUEVO_PRECIO, 'FM9999990D00') ||
                    '.',
                    1, 300
                ),
                V_PRECIO_ANTERIOR,
                'PENDIENTE'
            );
        END LOOP;
    END IF;
END REGISTRAR_PRECIO;

