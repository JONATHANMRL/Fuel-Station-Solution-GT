LEFT JOIN GASOLINERA GA
    ON G.ID_GASOLINERA = GA.ID_GASOLINERA
LEFT JOIN MARCA M
    ON GA.ID_MARCA = M.ID_MARCA
LEFT JOIN V_PRECIO_ACTUAL P
    ON G.ID_GASOLINERA = P.ID_GASOLINERA
;
