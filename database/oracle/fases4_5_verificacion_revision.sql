SELECT OWNER, OBJECT_NAME, STATUS FROM ALL_OBJECTS
WHERE OWNER = 'GASOLINAGT' AND OBJECT_NAME = 'REGISTRAR_PRECIO';

SELECT OWNER, OBJECT_NAME, ARGUMENT_NAME, POSITION, DATA_TYPE, IN_OUT
FROM ALL_ARGUMENTS WHERE OWNER = 'GASOLINAGT' AND OBJECT_NAME = 'REGISTRAR_PRECIO'
ORDER BY SEQUENCE;

SELECT LINE, TEXT FROM ALL_SOURCE
WHERE OWNER = 'GASOLINAGT' AND NAME = 'REGISTRAR_PRECIO' AND TYPE = 'PROCEDURE'
ORDER BY LINE;

SELECT DBTIMEZONE, SESSIONTIMEZONE, CURRENT_TIMESTAMP FROM DUAL;

-- Consultar las preferencias del titular autorizado; no copiar las del usuario 1.
-- :id_usuario es un bind; elegir conscientemente la cuenta humana de la prueba.
SELECT ID_PREFERENCIA, ID_USUARIO, ID_COMBUSTIBLE, PRECIO_MAXIMO, ESTADO
FROM GASOLINAGT.PREFERENCIA_ALERTA WHERE ID_USUARIO = :id_usuario;

SELECT ID_NOTIFICACION, ID_USUARIO, ID_PRECIO, ESTADO, FECHA_NOTIFICACION
FROM GASOLINAGT.NOTIFICACION WHERE ID_USUARIO = :id_usuario
ORDER BY FECHA_NOTIFICACION DESC, ID_NOTIFICACION DESC;

SELECT ID_GASOLINERA, ID_COMBUSTIBLE, PRECIO_ACTUAL, DISPONIBILIDAD
FROM GASOLINAGT.V_PRECIO_ACTUAL ORDER BY ID_GASOLINERA, ID_COMBUSTIBLE;

